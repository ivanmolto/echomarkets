export type GenInput = {
  slug: TemplateSlug
  market: Market
  outcomeIndex: number
  signalToken: string
  baseUrl: string // https://www.echomarkets.xyz
  params: Record<string, string | number | undefined>
}

const num = (v: unknown, d: number) => (v === undefined || v === '' || Number.isNaN(Number(v)) ? d : Number(v))

export function generate(input: GenInput): string {
  switch (input.slug) {
    case 'signal-follow': return signalFollow(input)
    case 'event-trigger': return eventTrigger(input)
    case 'mean-reversion': return meanReversion(input)
  }
}

function header(input: GenInput, title: string) {
  const m = input.market
  return `# ${title} — generated by EchoMarkets (${input.baseUrl})
# Market:  ${m.question}
# Slug:    ${m.slug}   (id ${m.id})
# Outcome: ${m.outcomes[input.outcomeIndex]}   token ${m.tokenIds[input.outcomeIndex]}
# Signal token valid 24h from generation. Re-purchase the template to refresh it.
#
# No Dawn yet?           npm i -g @dawnai/cli && dawn start
# First time only:       dawn consent accept && dawn auth login
# Run (paper, default):  dawn strategy launch ${input.slug}.py --name ${input.slug}-${m.slug.slice(0, 24)}
# Run (live):            ... --live --budget 20        (needs: dawn wallet use <name>; POL funded via dawn wallet fund)
# Watch:                 dawn strategy logs <run_id> --tail 50
# Stop:                  dawn strategy stop <run_id>   (stopping never sells positions)
#
# No private keys, no x402 inside this process: PayBox paid for this file; the strategy only does an authenticated GET.

import json
import time
import urllib.request
from datetime import datetime, timezone
from decimal import Decimal
from dawnai.strategy.tools import (
    get_polymarket_prices,
    polymarket_simulate_buy,
    polymarket_buy_token,
    read_portfolio,
    read_budget,
)

ECHO_BASE = ${JSON.stringify(input.baseUrl)}
ECHO_TOKEN = ${JSON.stringify(input.signalToken)}
MARKET = ${JSON.stringify(m.slug)}
OUTCOME_INDEX = ${input.outcomeIndex}
TOKEN_ID = ${JSON.stringify(m.tokenIds[input.outcomeIndex])}


def log(**kw):
    kw.setdefault("ts", datetime.now(timezone.utc).isoformat())
    print(json.dumps(kw, default=str))


def echo_get(path):
    req = urllib.request.Request(
        f"{ECHO_BASE}{path}",
        headers={"Authorization": f"Bearer {ECHO_TOKEN}", "Accept": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.loads(r.read())


def headroom_ok(size_usd):  # noqa: E302  (uses _get defined below; Python resolves at call time)
    b = read_budget()
    remaining = Decimal(str(_get(b, "remaining", 0)))
    if remaining < size_usd:
        log(event="skip", reason="would_exceed_budget", remaining=str(remaining), size=str(size_usd))
        return False
    return True


MIN_BUY_USD = Decimal("1.01")        # Polymarket minimum; anything less is rejected before chain
MAX_PRICE_IMPACT = Decimal("0.01")   # 1% — if simulate_buy shows more, bumping slippage only buys a worse fill
SLIPPAGE_BPS = 100                   # Dawn default; bounds worst-case fill, trade reverts if the book moves more


def _get(obj, key, default=None):
    """SDK results may be dicts or objects; read either."""
    if isinstance(obj, dict):
        return obj.get(key, default)
    return getattr(obj, key, default)


def guarded_buy(size_usd):
    if size_usd < MIN_BUY_USD:
        log(event="skip", reason="below_min_buy", size=str(size_usd), min=str(MIN_BUY_USD))
        return None
    sim = polymarket_simulate_buy(TOKEN_ID, size_usd)
    if _get(sim, "success", True) is False:
        log(event="skip", reason="simulate_failed", detail=_get(sim, "error") or _get(sim, "message"))
        return None
    impact = _get(sim, "price_impact")
    avg_price = _get(sim, "expected_average_price") or _get(sim, "executed_price")
    log(event="simulate", size=str(size_usd), avg_price=avg_price, price_impact=impact)
    if impact is not None and Decimal(str(impact)) > MAX_PRICE_IMPACT:
        log(event="skip", reason="price_impact", impact=impact, max=str(MAX_PRICE_IMPACT))
        return None
    res = polymarket_buy_token(TOKEN_ID, size_usd, slippage_bps=SLIPPAGE_BPS)
    log(event="buy", size=str(size_usd), avg_price=avg_price, result=res)
    return res


# Register this run with Dawn's API early so it shows in the dashboard (local paper runs only
# appear once they've called a portfolio/trade tool).
try:
    _pf = read_portfolio()
    log(event="portfolio", positions=len(_get(_get(_pf, "wallet", {}), "positions", []) or []))
except Exception as _e:
    log(event="portfolio_error", error=repr(_e))
`
}

function footer(hours: number, intervalMinutes: number) {
  return `

HOURS = ${hours}
INTERVAL_MINUTES = ${intervalMinutes}
ITERATIONS = int((HOURS * 60) / INTERVAL_MINUTES)

log(event="start", market=MARKET, token=TOKEN_ID, iterations=ITERATIONS)
for i in range(ITERATIONS):
    try:
        run_once(i)
    except Exception as exc:
        log(event="error", iter=i, error=repr(exc))
    time.sleep(INTERVAL_MINUTES * 60)
log(event="done")
`
}

function signalFollow(input: GenInput): string {
  const threshold = num(input.params.threshold, 0.7)
  const size = num(input.params.size_usd, 5)
  return header(input, 'Signal follow') + `
THRESHOLD = ${threshold}
SIZE_USD = Decimal("${size}")
MAX_BUYS = ${num(input.params.max_buys, 3)}
buys_done = 0


def run_once(i):
    global buys_done
    if buys_done >= MAX_BUYS:
        log(event="idle", reason="max_buys_reached")
        return
    sig = echo_get(f"/api/signal/{MARKET}?outcome={OUTCOME_INDEX}")
    log(event="signal", direction=sig["direction"], confidence=sig["confidence"], price=sig["price"], reasoning=sig["reasoning"])
    if sig["direction"] != "buy" or sig["confidence"] < THRESHOLD:
        return
    if not headroom_ok(SIZE_USD):
        return
    if guarded_buy(SIZE_USD) is not None:
        buys_done += 1
` + footer(num(input.params.hours, 24), num(input.params.interval_minutes, 10))
}

function eventTrigger(input: GenInput): string {
  const feed = String(input.params.feed_url ?? 'https://earthquake.usgs.gov/earthquakes/feed/v1.0/summary/all_hour.geojson')
  const size = num(input.params.size_usd, 5)
  return header(input, 'Event trigger') + `
FEED_URL = ${JSON.stringify(feed)}
WINDOW_START = ${JSON.stringify(input.params.window_start ?? '')}  # ISO 8601, empty = now
WINDOW_END = ${JSON.stringify(input.params.window_end ?? '')}      # ISO 8601, empty = no end
SIZE_USD = Decimal("${size}")
fired = False


def in_window():
    now = datetime.now(timezone.utc)
    if WINDOW_START and now < datetime.fromisoformat(WINDOW_START):
        return False
    if WINDOW_END and now > datetime.fromisoformat(WINDOW_END):
        return False
    return True


def condition(feed):
    # EDIT ME: return True when the event you are trading has happened.
    # Default: any earthquake >= 7.0 in the USGS last-hour feed.
    for f in feed.get("features", []):
        mag = (f.get("properties") or {}).get("mag")
        if mag is not None and float(mag) >= 7.0:
            return True
    return False


def run_once(i):
    global fired
    if fired:
        return
    if not in_window():
        log(event="idle", reason="outside_window")
        return
    with urllib.request.urlopen(FEED_URL, timeout=15) as r:
        feed = json.loads(r.read())
    if not condition(feed):
        log(event="poll", fired=False)
        return
    log(event="trigger", feed=FEED_URL)
    if headroom_ok(SIZE_USD) and guarded_buy(SIZE_USD) is not None:
        fired = True
` + footer(num(input.params.hours, 24), num(input.params.interval_minutes, 1))
}

function meanReversion(input: GenInput): string {
  const drop = num(input.params.drop_pct, 8)
  const lookback = num(input.params.lookback_minutes, 30)
  const size = num(input.params.size_usd, 5)
  return header(input, 'Mean reversion') + `
DROP_PCT = Decimal("${drop}")
LOOKBACK_MINUTES = ${lookback}
SIZE_USD = Decimal("${size}")
MAX_BUYS = ${num(input.params.max_buys, 2)}
history = []  # (ts, price)
buys_done = 0


def current_price():
    prices = get_polymarket_prices(TOKEN_ID)
    return Decimal(str(_get(prices, "prices", {})[TOKEN_ID]["BUY"]))


def run_once(i):
    global buys_done
    now = time.time()
    p = current_price()
    history.append((now, p))
    cutoff = now - LOOKBACK_MINUTES * 60
    while history and history[0][0] < cutoff:
        history.pop(0)
    baseline = max(h[1] for h in history)
    drop = (baseline - p) / baseline * 100 if baseline > 0 else Decimal("0")
    log(event="tick", price=str(p), baseline=str(baseline), drop_pct=str(round(drop, 2)))
    if buys_done >= MAX_BUYS or drop < DROP_PCT:
        return
    if headroom_ok(SIZE_USD) and guarded_buy(SIZE_USD) is not None:
        buys_done += 1
` + footer(num(input.params.hours, 24), num(input.params.interval_minutes, 2))
}
